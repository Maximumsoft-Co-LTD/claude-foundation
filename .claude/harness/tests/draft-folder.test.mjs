function writeStartFolder(root, files) {
  const dir = join(root, ".foundation", "drafts", "refund-api");
  rmSync(dir, { recursive: true, force: true });
  mkdirSync(dir, { recursive: true });
  for (const [name, content] of Object.entries(files))
    writeFileSync(join(dir, name), typeof content === "string" ? content : JSON.stringify(content));
  return ".foundation/drafts/refund-api";
}

function quiet(operation) {
  const log = console.log;
  const lines = [];
  console.log = (line) => lines.push(String(line));
  try { return { result: operation(), output: lines.join("\n") }; } finally { console.log = log; }
}

for (const [name, files, pattern] of [
  ["an unknown heading", { "change.json": startChangeJson(), "design.md": "## Overview\nx\n## Wishlist\ny\n" },
    /design\.md heading 'Wishlist' is not an outline section; accepted headings: Overview/],
  ["a harness-generated heading", { "change.json": startChangeJson(), "proposal.md": "## Acceptance traceability\nrows\n" },
    /Acceptance traceability is generated by the harness; remove it from proposal\.md/],
  ["out-of-order headings", { "change.json": startChangeJson(), "design.md": "## Risks\nr\n## Overview\no\n" },
    /'Risks' must come after 'Overview'; outline order is Overview, Risks/],
  ["a TODO in prose", { "change.json": startChangeJson(), "design.md": "## Overview\nTODO later\n" },
    /section 'Overview' contains TODO/],
  ["a missing change.json", { "design.md": "## Overview\nx\n" },
    /draft folder \.foundation\/drafts\/refund-api is missing change\.json/],
  ["an unknown change.json version", { "change.json": { ...startChangeJson(), version: 6 } },
    /change\.json must declare version 5/]
]) {
  test(`change start with ${name} returns a draft-repair EDIT and creates nothing`, (t) => {
    const { root, changes, lifecycle } = startProject(t);
    const path = writeStartFolder(root, files);
    for (const run of [() => lifecycle.startAtomic(path), () => lifecycle.inspectDraft(path)]) {
      const { result } = quiet(run);
      assert.equal(result.action, "EDIT");
      assert.equal(result.owner, "agent");
      assert.equal(result.intake.kind, "repair-draft");
      assert.match(result.intake.issues.join("\n"), pattern);
      assert.equal(result.resume, `claude-foundation change start ${path} --inspect`);
    }
    assert.equal(existsSync(join(changes, "refund-api")), false);
    assert.equal(existsSync(join(root, ".foundation", "runtime", "refund-api.json")), false);
  });
}

