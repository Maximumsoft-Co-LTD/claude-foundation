test("draftSource accepts a directory and surfaces folder issues as draft validation", (t) => {
  const root = mkdtempSync(join(tmpdir(), "foundation-draft-folder-root-"));
  t.after(() => rmSync(root, { recursive: true, force: true }));
  mkdirSync(join(root, "drafts", "broken"), { recursive: true });
  writeFileSync(join(root, "drafts", "broken", "design.md"), "## File map\nx\n");
  const lifecycle = lifecycleAt(root);
  assert.throws(() => lifecycle.loadDraft("drafts/broken"), (error) => {
    assert.match(error.message, /^semantic draft validation failed:/);
    assert.match(error.message, /draft folder drafts\/broken is missing change\.json/);
    assert.match(error.message, /File map is generated by the harness; remove it from design\.md/);
    return true;
  });

  // A valid folder passes draftSource; the v4/v5 semantic validation then judges
  // its fields, never the folder, the JSON file, or the version.
  mkdirSync(join(root, "drafts", "ok"));
  writeFileSync(join(root, "drafts", "ok", "change.json"), JSON.stringify(changeJson()));
  writeFileSync(join(root, "drafts", "ok", "design.md"), "## Overview\nx\n");
  assert.throws(() => lifecycle.loadDraft("drafts/ok"), (error) => {
    assert.match(error.message, /semantic draft validation failed/);
    assert.doesNotMatch(error.message, /version|JSON file|draft folder/);
    return true;
  });
});

